// قوالب أسئلة موجهة للذكاء الاصطناعي السياقي
export function buildCoachPrompt(input: {
  phase: 'preparation' | 'situation1' | 'situation2' | 'final';
  sessionTitle?: string;
  educationalObjective?: string;
  contingency?: ContingencyMode;
  planContext?: string;
}): string {
  const phaseNames: Record<string, string> = {
    preparation: 'المرحلة التحضيرية (إحماء)',
    situation1: 'الوضعية التعلمية الأولى (بناء التعلمات)',
    situation2: 'الوضعية التعلمية الثانية (التنافس والتطبيق)',
    final: 'المرحلة الختامية (التهدئة والتقويم)',
  };
  const contingencyNames: Record<string, string> = {
    normal: 'ظروف عادية',
    hot_weather: 'طقس حار — تقليل الجهد وزيادة الترطيب',
    equipment_shortage: 'نقص عتاد — أنشطة بديلة',
    high_fatigue: 'إرهاق — أنشطة خفيفة',
  };
  return `أنا أستاذ تربية بدنية في الطور الابتدائي، أدير حالياً ${phaseNames[input.phase]} في حصة بعنوان "${input.sessionTitle || 'حصة بيداغوجية'}".
الهدف التعلمي: ${input.educationalObjective || 'تنمية المهارات الحركية والتوافق البدني'}.
الظروف: ${input.contingency ? contingencyNames[input.contingency] : 'ظروف عادية'}.
${input.planContext ? `سياق المذكرة: ${input.planContext}` : ''}
قدّم 3 نصائح عملية قصيرة جداً وواضحة أطبّقها فوراً في الميدان الآن (بالعربية، بدون مقدمات، على شكل قائمة).`;
}
